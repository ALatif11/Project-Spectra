"""Generate the EchoProof ad shots through the Higgsfield API (pip install higgsfield-client).

    python ad/generate_ad.py --plan              # free: show every prompt and argument, no API calls
    python ad/generate_ad.py still_establishing  # generate one shot (asks before spending)
    python ad/generate_ad.py --all               # every shot not already done, in order
    python ad/generate_ad.py gen_a --redo        # regenerate a shot that is already done

Credentials: set HF_KEY="key_id:key_secret" in your environment (never commit it).
Outputs and a manifest go to ad/output/. Shots recorded in the manifest are skipped, so a paid
shot is never regenerated by accident.
"""

import argparse
import json
import re
import sys
import urllib.request
from pathlib import Path

HERE = Path(__file__).resolve().parent
OUT = HERE / "output"
MANIFEST = OUT / "manifest.json"


def load_config(path: Path = HERE / "shots.json") -> dict:
    return json.loads(path.read_text(encoding="utf-8"))


def expand(text: str, blocks: dict) -> str:
    return re.sub(r"\{([A-Z]+)\}", lambda m: blocks.get(m.group(1), m.group(0)), text)


def unfilled(value) -> bool:
    return not isinstance(value, str) or value.startswith("FILL_ME") or not value.strip()


MAX_SHOT_PROMPT = 512  # Kling multi_prompt item limit (model page schema)


def model_key(shot: dict) -> str:
    return "video_from_image" if shot["kind"] == "video" and shot.get("start_image") else shot["kind"]


def build(cfg: dict, shot: dict, uploaded: dict) -> tuple[str, dict]:
    """(model id, API arguments) for one shot. `uploaded` maps earlier shot names to hosted URLs."""
    kind, names, blocks = shot["kind"], cfg["arg_names"], cfg["blocks"]
    args = {**cfg["defaults"].get(kind, {}), **shot.get("args", {})}
    args[names["prompt"]] = expand(shot["prompt"], blocks)
    if shot.get("multi"):  # Kling native multi-shot
        args["multi_shots"] = True
        args["multi_prompt"] = [{"prompt": expand(m["prompt"], blocks), "duration": m["duration"]} for m in shot["multi"]]
        args[names["duration"]] = sum(m["duration"] for m in shot["multi"])
    elif "duration" in shot:
        args[names["duration"]] = shot["duration"]
    for key in ("start_image", "end_image"):
        if shot.get(key) and not unfilled(names.get(key)):
            args[names[key]] = uploaded.get(shot[key], f"<url of {shot[key]}>")
    return cfg["models"][model_key(shot)], args


def problems(cfg: dict, shot: dict) -> list[str]:
    out = []
    if unfilled(cfg["models"].get(model_key(shot))):
        out.append(f"models.{model_key(shot)} is not filled in")
    if shot.get("start_image") and unfilled(cfg["arg_names"].get("start_image")):
        out.append("arg_names.start_image is not filled in (needed for the start frame)")
    if shot.get("multi"):
        _, args = build(cfg, shot, {})
        for i, m in enumerate(args["multi_prompt"], 1):
            if len(m["prompt"]) > MAX_SHOT_PROMPT:
                out.append(f"shot {i} prompt is {len(m['prompt'])} characters (limit {MAX_SHOT_PROMPT})")
        if not 3 <= args[cfg["arg_names"]["duration"]] <= 15:
            out.append("total duration must be 3-15 seconds")
    return out


def find_url(result) -> str | None:
    """First media URL anywhere in the result JSON (images[0].url, video.url, audio.url, ...)."""
    if isinstance(result, dict):
        if isinstance(result.get("url"), str):
            return result["url"]
        values = result.values()
    elif isinstance(result, list):
        values = result
    else:
        return None
    for v in values:
        if (u := find_url(v)):
            return u
    return None


def download(url: str, name: str) -> Path:
    suffix = Path(url.split("?")[0]).suffix or ".bin"
    dest = OUT / f"{name}{suffix}"
    with urllib.request.urlopen(url, timeout=300) as r:
        dest.write_bytes(r.read())
    return dest


def read_manifest() -> dict:
    try:
        return json.loads(MANIFEST.read_text(encoding="utf-8"))
    except (OSError, ValueError):
        return {}


def run(cfg: dict, names: list[str], redo: bool, yes: bool) -> int:
    import higgsfield_client as hf

    OUT.mkdir(exist_ok=True)
    (OUT / ".gitignore").write_text("*\n", encoding="utf-8")  # generated media never goes into Git
    manifest = read_manifest()
    shots = {s["name"]: s for s in cfg["shots"]}
    todo = [n for n in names if redo or n not in manifest]
    for n in names:
        if n in manifest and not redo:
            print(f"skip {n}: already done -> {manifest[n]['file']} (use --redo to pay for it again)")
    if not todo:
        return 0
    blocking = {n: problems(cfg, shots[n]) for n in todo if problems(cfg, shots[n])}
    if blocking:
        for n, p in blocking.items():
            print(f"cannot run {n}: " + "; ".join(p))
        print("Fill these in ad/shots.json from the model pages in your Higgsfield dashboard.")
        return 2
    if not yes and input(f"Generate {', '.join(todo)}? This spends API credits. [y/N] ").strip().lower() != "y":
        print("Cancelled; nothing was submitted.")
        return 1

    uploaded = {}
    for n in todo:
        shot = shots[n]
        for ref in (shot.get("start_image"), shot.get("end_image")):
            if ref and ref not in uploaded:
                if ref not in manifest:
                    print(f"{n} needs {ref} first; run: python ad/generate_ad.py {ref}")
                    return 2
                uploaded[ref] = hf.upload_file(manifest[ref]["file"])
        model, args = build(cfg, shot, uploaded)
        print(f"-> {n} on {model} ...", flush=True)
        try:
            result = hf.subscribe(model, arguments=args,
                                  on_enqueue=lambda rid: print(f"   queued as request {rid}", flush=True))
        except hf.InsufficientCreditsError:
            print("Out of API credits. Top up in the Higgsfield dashboard, then rerun; finished shots are kept.")
            return 3
        except hf.HiggsfieldClientError as exc:
            print(f"   {n} failed: {exc}. Nothing was saved for this shot; check the model id and argument names.")
            return 4
        (OUT / f"{n}.result.json").write_text(json.dumps(result, indent=2), encoding="utf-8")
        url = find_url(result)
        if not url:
            print(f"   {n}: no media URL in the result; see output/{n}.result.json")
            return 4
        path = download(url, n)
        manifest[n] = {"file": str(path), "url": url, "model": model}
        MANIFEST.write_text(json.dumps(manifest, indent=2), encoding="utf-8")
        print(f"   saved {path}")
    return 0


def plan(cfg: dict) -> None:
    for shot in cfg["shots"]:
        model, args = build(cfg, shot, {})
        issues = problems(cfg, shot)
        print(f"=== {shot['name']} ({shot['kind']}) model: {model}")
        print(json.dumps(args, indent=2))
        print("    BLOCKED: " + "; ".join(issues) if issues else "    ready", "\n")


def selftest() -> None:
    assert expand("a {X} {Y}", {"X": "b"}) == "a b {Y}"
    assert find_url({"images": [{"url": "https://x/i.png"}]}) == "https://x/i.png"
    assert find_url({"status": "ok", "video": {"url": "https://x/v.mp4"}}) == "https://x/v.mp4"
    assert find_url({"nothing": 1}) is None
    cfg = load_config()
    names = [s["name"] for s in cfg["shots"]]
    assert len(names) == len(set(names)), "duplicate shot names"
    for s in cfg["shots"]:
        for ref in (s.get("start_image"), s.get("end_image")):
            assert ref is None or names.index(ref) < names.index(s["name"]), f"{s['name']} uses {ref} before it exists"
        assert not re.search(r"\{[A-Z]+\}", json.dumps(build(cfg, s, {})[1])), f"unknown block in {s['name']}"
        if s["kind"] != "speech":
            assert not problems(cfg, s), f"{s['name']}: {problems(cfg, s)}"
    print("selftest ok")


def main() -> int:
    p = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    p.add_argument("shots", nargs="*", help="shot names from ad/shots.json")
    p.add_argument("--all", action="store_true", help="every shot, in order")
    p.add_argument("--plan", action="store_true", help="print prompts and arguments; no API calls")
    p.add_argument("--redo", action="store_true", help="regenerate shots already in the manifest")
    p.add_argument("--yes", action="store_true", help="skip the spend confirmation")
    p.add_argument("--selftest", action="store_true")
    a = p.parse_args()
    cfg = load_config()
    if a.selftest:
        selftest()
        return 0
    if a.plan:
        plan(cfg)
        return 0
    names = a.shots
    if a.all:
        names = []
        for s in cfg["shots"]:
            if unfilled(cfg["models"].get(model_key(s))):
                print(f"skip {s['name']}: models.{model_key(s)} is not set")
            else:
                names.append(s["name"])
    unknown = [n for n in names if n not in {s["name"] for s in cfg["shots"]}]
    if not names or unknown:
        p.error(f"unknown shots: {unknown}" if unknown else "name shots to generate, or use --all / --plan")
    return run(cfg, names, a.redo, a.yes)


if __name__ == "__main__":
    sys.exit(main())
